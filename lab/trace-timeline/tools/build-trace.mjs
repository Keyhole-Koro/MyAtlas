#!/usr/bin/env node
// Writes data/trace-full.js (window.TRACE_FULL) from the recorded run in MyComputer.
//
//   node lab/trace-timeline/tools/build-trace.mjs [path/to/ui-request.json]
//
// lab/data/atlas.json carries the same run, but MyAtlas's traces.py keeps only enter, irq, switch
// and request events. The timeline needs the exits (and irets) too, to know how long each call
// lasted, so this copies every event of the original file, without the timer clock.
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { createHash } from "node:crypto";

const HERE = resolve(import.meta.dirname, "..");
const src = process.argv[2] ?? resolve(process.env.HOME, "Workspaces/MyComputer/docs/atlas/traces/ui-request.json");
const text = await readFile(src, "utf8");
const t = JSON.parse(text);
const KEEP = ["seq", "instr", "thread", "program", "fn", "ev", "cause", "trap", "syscall", "service", "interrupted", "from", "method", "unwound"];
const events = t.events.map((e) => {
  const x = {};
  for (const k of KEEP) if (e[k] !== undefined && e[k] !== null) x[k] = e[k];
  return x;
});
const watched = {};
for (const w of t.watched ?? []) watched[w.fn] = { program: w.program, file: w.file || null };
const out = {
  source: "docs/atlas/traces/" + src.split("/").pop(),
  sha1: createHash("sha1").update(text).digest("hex").slice(0, 12),
  title: t.title, date: t.date, run: t.run, fields: t.fields, threads: t.threads,
  watched, events,
};
const js = "// Generated by tools/build-trace.mjs from MyComputer's " + out.source + ". Do not edit.\n"
  + "window.TRACE_FULL = " + JSON.stringify(out) + ";\n";
await writeFile(resolve(HERE, "data/trace-full.js"), js);
const kinds = {};
for (const e of events) kinds[e.ev] = (kinds[e.ev] || 0) + 1;
console.log(`${events.length} events`, kinds, `${(js.length / 1024).toFixed(1)} KB`);
